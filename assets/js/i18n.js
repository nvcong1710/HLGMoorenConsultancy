  // ─── Core ──────────────────────────────────────────────────────────────────

  function getCurrentLang() {
    return localStorage.getItem("hlg_lang") || "en";
  }

  function setLang(lang) {
    localStorage.setItem("hlg_lang", lang);
    document.documentElement.lang = lang;
    applyI18n(lang);
    _updateLangButton(lang);
    window.dispatchEvent(new CustomEvent("langChange", { detail: { lang } }));
  }

  function toggleLang() {
    setLang(getCurrentLang() === "en" ? "vi" : "en");
  }

  function getTranslation(lang, key) {
    const keys = key.split(".");
    let obj = translations[lang];
    for (const k of keys) {
      if (obj == null) return undefined;
      obj = obj[k];
    }
    return obj;
  }

  // Apply all [data-i18n] and [data-i18n-placeholder] in the document
  function applyI18n(lang) {
    document.querySelectorAll("[data-i18n]").forEach(function (el) {
      const val = getTranslation(lang, el.getAttribute("data-i18n"));
      if (typeof val === "string") el.innerHTML = val;
    });
    document.querySelectorAll("[data-i18n-placeholder]").forEach(function (el) {
      const val = getTranslation(
        lang,
        el.getAttribute("data-i18n-placeholder"),
      );
      if (typeof val === "string") el.placeholder = val;
    });
  }

  function _updateLangButton(lang) {
    const pairs = [
      [document.getElementById("lang-en"), document.getElementById("lang-vi")],
      [
        document.getElementById("lang-en-mobile"),
        document.getElementById("lang-vi-mobile"),
      ],
    ];
    pairs.forEach(function ([enEl, viEl]) {
      if (!enEl || !viEl) return;
      if (lang === "en") {
        enEl.className = "font-bold text-[#FF7E29]";
        viEl.className = "font-semibold text-white/40";
      } else {
        viEl.className = "font-bold text-[#FF7E29]";
        enEl.className = "font-semibold text-white/40";
      }
    });
  }

  // ─── Blog helpers ──────────────────────────────────────────────────────────

  /** Get the localized property of a blog entry. Falls back to top-level key. */
  function getBlogLocalized(blog, key) {
    const lang = getCurrentLang();
    if (blog[lang] && blog[lang][key] !== undefined) return blog[lang][key];
    return blog[key];
  }

  /** Format "3 min read" → "3 phút đọc" for vi */
  function formatReadTime(readTime, lang) {
    if (!readTime) return "";
    lang = lang || getCurrentLang();
    if (lang === "vi") {
      const num = (readTime.match(/\d+/) || [""])[0];
      return num + " phút đọc";
    }
    return readTime;
  }

  /** Format date using locale */
  function formatDate(dateString, lang) {
    if (!dateString) return "";
    lang = lang || getCurrentLang();
    const opts = { year: "numeric", month: "long", day: "numeric" };
    try {
      return new Date(dateString).toLocaleDateString(
        lang === "vi" ? "vi-VN" : "en-US",
        opts,
      );
    } catch (e) {
      return dateString;
    }
  }

